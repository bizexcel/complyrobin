<?php

use App\Core\Access\Enums\SystemRole;
use App\Core\Identity\Models\User;
use App\Core\Organisations\Actions\CreateOrganisation;
use App\Core\People\Models\Person;
use App\Core\Tenancy\Facades\Tenancy;
use App\Filament\App\Resources\Credentials\Pages\ViewCredential;
use App\Modules\Credentials\Actions\RecordRotation;
use App\Modules\Credentials\Actions\RevokeCredential;
use App\Modules\Credentials\Actions\UpdateCredential;
use App\Modules\Credentials\Models\Application;
use App\Modules\Credentials\Models\Credential;
use App\Modules\Credentials\Models\CredentialRotation;
use Illuminate\Auth\Access\AuthorizationException;
use Illuminate\Database\QueryException;
use Illuminate\Support\Carbon;
use Illuminate\Support\Facades\DB;
use Illuminate\Validation\ValidationException;
use Livewire\Livewire;

beforeEach(function (): void {
    $this->travelTo(Carbon::parse('2026-06-01 03:00', 'UTC'));
    $this->owner = User::factory()->create();
    $this->organisation = app(CreateOrganisation::class)->handle($this->owner, 'Acme');
    $this->application = Tenancy::run($this->organisation, fn () => Application::factory()->create());
});

function credentialFor(array $attributes = []): Credential
{
    // refresh(): the due date is generated by the database, so load it.
    return Tenancy::run(test()->organisation, fn () => Credential::factory()->create(['application_id' => test()->application->id, ...$attributes])->refresh());
}

function rotate(User $actor, Credential $credential, array $data = []): CredentialRotation
{
    return Tenancy::run(test()->organisation, fn (): CredentialRotation => app(RecordRotation::class)->handle($actor, $credential, $data));
}

it('records the rotation and moves the due date on by the interval', function (): void {
    $credential = credentialFor(['rotation_days' => 90, 'last_rotated_at' => '2026-04-01 03:00:00']);
    $wasDue = $credential->next_rotation_at;

    $rotation = rotate($this->owner, $credential, ['notes' => 'New token in Laravel Cloud prod']);

    expect($rotation->due_at->equalTo($wasDue))->toBeTrue()
        ->and($rotation->rotated_by_id)->toBe($this->owner->id)
        ->and($credential->next_rotation_at->toDateString())->toBe('2026-08-30')
        ->and($rotation->isOnTime('Asia/Kuala_Lumpur'))->toBeTrue();
});

it('keeps a late rotation marked late', function (): void {
    $credential = credentialFor(['rotation_days' => 30, 'last_rotated_at' => '2026-04-01 03:00:00']);

    $rotation = rotate($this->owner, $credential);

    expect($rotation->isOnTime('Asia/Kuala_Lumpur'))->toBeFalse()
        ->and($credential->next_rotation_at->toDateString())->toBe('2026-07-01');
});

it('asks for the new expiry when the credential expires', function (): void {
    $credential = credentialFor(['rotation_days' => null, 'expires_at' => '2026-06-10 00:00:00']);

    expect(fn (): CredentialRotation => rotate($this->owner, $credential))->toThrow(ValidationException::class);

    rotate($this->owner, $credential, ['expires_at' => '2027-06-10 00:00:00']);
    expect($credential->next_rotation_at->toDateString())->toBe('2027-06-10');
});

it('lets the credential\'s owner or backup record a rotation, even as a Viewer, but not another Viewer', function (): void {
    [$ownerUser, $backupUser, $otherViewer] = [
        memberWithRole($this->organisation, SystemRole::Viewer),
        memberWithRole($this->organisation, SystemRole::Viewer),
        memberWithRole($this->organisation, SystemRole::Viewer),
    ];
    [$ownerPerson, $backupPerson] = Tenancy::run($this->organisation, fn (): array => [
        Person::factory()->create(['user_id' => $ownerUser->id]),
        Person::factory()->create(['user_id' => $backupUser->id]),
    ]);
    $credential = credentialFor(['owner_id' => $ownerPerson->id, 'backup_owner_id' => $backupPerson->id, 'last_rotated_at' => '2026-03-01 00:00:00']);

    rotate($ownerUser, $credential, ['rotated_at' => '2026-05-01 00:00:00']);
    rotate($backupUser, $credential, ['rotated_at' => '2026-05-20 00:00:00']);

    expect(fn (): CredentialRotation => rotate($otherViewer, $credential))->toThrow(AuthorizationException::class);
});

it('refuses a rotation in the future or before the last one', function (string $rotatedAt): void {
    $credential = credentialFor(['last_rotated_at' => '2026-05-01 00:00:00']);

    rotate($this->owner, $credential, ['rotated_at' => $rotatedAt]);
})->with([
    'in the future' => '2026-06-02 00:00:00',
    'before the last rotation' => '2026-04-15 00:00:00',
])->throws(ValidationException::class);

it('refuses to rotate a revoked credential', function (): void {
    $credential = credentialFor();
    Tenancy::run($this->organisation, fn () => app(RevokeCredential::class)->handle($this->owner, $credential));

    rotate($this->owner, $credential);
})->throws(ValidationException::class, 'revoked');

it('refuses notes that contain a key', function (): void {
    rotate($this->owner, credentialFor(), ['notes' => 'new key is sk_live_51HxYzAbCdEfGhIjKlMn']);
})->throws(ValidationException::class);

it('never lets the app change or delete a recorded rotation', function (string $statement): void {
    rotate($this->owner, credentialFor());

    Tenancy::run($this->organisation, fn () => DB::statement($statement));
})->with([
    'update' => "update credential_rotations set rotated_at = now() - interval '1 year'",
    'delete' => 'delete from credential_rotations',
])->throws(QueryException::class, 'permission denied');

it('takes the last rotation from recorded rotations once there are some', function (): void {
    $credential = credentialFor();
    rotate($this->owner, $credential);

    Tenancy::run($this->organisation, fn () => app(UpdateCredential::class)->handle($this->owner, $credential, [
        'application_id' => $this->application->id, 'name' => 'CI token', 'type' => 'api_token', 'environment' => 'production',
        'rotation_days' => 90, 'last_rotated_at' => '2026-01-01 00:00:00',
    ]));
})->throws(ValidationException::class, 'Record a rotation');

it('records a rotation from the credential\'s page', function (): void {
    $credential = credentialFor();
    openOrganisationAs($this->owner, $this->organisation);

    Livewire::test(ViewCredential::class, ['record' => $credential->getRouteKey()])
        ->callAction('recordRotation', ['rotated_at' => now()->subHour()->toDateTimeString(), 'notes' => 'Rotated in the vendor console'])
        ->assertHasNoActionErrors();

    expect($credential->rotations()->count())->toBe(1);
});
