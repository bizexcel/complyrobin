<?php

namespace App\Modules\Credentials\Models;

use App\Core\Audit\Concerns\LogsTenantActivity;
use App\Core\Organisations\Models\Organisation;
use App\Core\People\Models\Person;
use App\Core\Tenancy\Concerns\BelongsToOrganisation;
use App\Modules\Credentials\Enums\CredentialStatus;
use App\Modules\Credentials\Enums\CredentialType;
use App\Modules\Credentials\Enums\Environment;
use App\Modules\Credentials\Support\RotationSchedule;
use Carbon\CarbonInterface;
use Database\Factories\CredentialFactory;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Attributes\UseFactory;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Concerns\HasUuids;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\SoftDeletes;
use Illuminate\Support\Carbon;

/**
 * What the organisation knows about one credential: where it is used, who owns it and when it is due. Never the
 * secret itself.
 *
 * @property string $reference
 * @property string $name
 * @property CredentialType $type
 * @property Environment $environment
 * @property string $application_id
 * @property string|null $owner_id
 * @property string|null $backup_owner_id
 * @property string|null $used_in
 * @property string|null $hint
 * @property int|null $rotation_days
 * @property Carbon|null $last_rotated_at
 * @property Carbon|null $expires_at
 * @property Carbon|null $revoked_at
 * @property Carbon|null $next_rotation_at generated by the database
 */
#[Fillable(['application_id', 'name', 'type', 'environment', 'owner_id', 'backup_owner_id', 'used_in', 'hint', 'rotation_days', 'last_rotated_at', 'expires_at'])]
#[UseFactory(CredentialFactory::class)]
class Credential extends Model
{
    /** @use HasFactory<CredentialFactory> */
    use BelongsToOrganisation, HasFactory, HasUuids, LogsTenantActivity, SoftDeletes;

    /**
     * @return BelongsTo<Application, $this>
     */
    public function application(): BelongsTo
    {
        return $this->belongsTo(Application::class);
    }

    /**
     * @return BelongsTo<Person, $this>
     */
    public function owner(): BelongsTo
    {
        return $this->belongsTo(Person::class);
    }

    /**
     * @return BelongsTo<Person, $this>
     */
    public function backupOwner(): BelongsTo
    {
        return $this->belongsTo(Person::class);
    }

    public function status(?CarbonInterface $now = null, ?string $timezone = null): CredentialStatus
    {
        return RotationSchedule::status(
            $this->next_rotation_at,
            $this->expires_at,
            $this->revoked_at,
            $now ?? now(),
            $timezone ?? $this->timezone(),
            (int) config('credentials.due_soon_days'),
        );
    }

    /**
     * Credentials still counting towards the plan's limit: not revoked and not deleted.
     *
     * @param  Builder<Credential>  $query
     */
    public function scopeActive(Builder $query): void
    {
        $query->whereNull('revoked_at');
    }

    private function timezone(): string
    {
        $organisation = $this->organisation;

        return $organisation instanceof Organisation ? $organisation->timezone : (string) config('app.timezone');
    }

    /**
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'type' => CredentialType::class,
            'environment' => Environment::class,
            'rotation_days' => 'integer',
            'last_rotated_at' => 'datetime',
            'expires_at' => 'datetime',
            'revoked_at' => 'datetime',
            'next_rotation_at' => 'datetime',
        ];
    }
}
